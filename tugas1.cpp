// Question are, Buat Program untuk mencari nilai P, Q, R jika diketahui P=0, Q=5 dan R=10. Kemudian diberikan algoritma P=Q, Q=R

#include <iostream> 
using namespace std;

int main() {
    int p, q, r;

    p = 0;
    q = 5;
    r = 10;

    p = q;
    q = r;

    cout << "p = " << p << endl;
    cout << "q = " << q << endl;
    cout << "r = " << r << endl;

    return 0;
}